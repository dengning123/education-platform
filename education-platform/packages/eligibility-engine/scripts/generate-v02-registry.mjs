function nfc(s) {
  return s.normalize("NFC");
}

function escapeJsonString(s) {
  let out = "\"";
  for (const ch of nfc(s)) {
    const code = ch.codePointAt(0);
    if (ch === "\\") out += "\\\\";
    else if (ch === "\"") out += "\\\"";
    else if (code === 0x08) out += "\\b";
    else if (code === 0x0c) out += "\\f";
    else if (code === 0x0a) out += "\\n";
    else if (code === 0x0d) out += "\\r";
    else if (code === 0x09) out += "\\t";
    else if (code < 0x20) out += `\\u${code.toString(16).padStart(4, "0")}`;
    else out += ch;
  }
  return `${out}"`;
}

function canonicalNumber(n) {
  if (!Number.isFinite(n)) throw new Error("NaN/infinity forbidden");
  if (Object.is(n, -0)) return "0";
  const s = n.toString();
  if (s.includes("e") || s.includes("E")) {
    return Number(n).toFixed(20).replace(/\.?0+$/, "") || "0";
  }
  if (s.includes(".")) return s.replace(/0+$/, "").replace(/\.$/, "");
  return s;
}

function canonicalize(value) {
  if (value === null) return "null";
  if (typeof value === "boolean") return value ? "true" : "false";
  if (typeof value === "number") return canonicalNumber(value);
  if (typeof value === "string") return escapeJsonString(value);
  if (Array.isArray(value)) {
    return `[${value.map((v) => canonicalize(v)).join(",")}]`;
  }
  if (typeof value === "object") {
    const keys = Object.keys(value).map(nfc).sort((a, b) => {
      if (a < b) return -1;
      if (a > b) return 1;
      return 0;
    });
    const seen = new Set();
    for (const k of keys) {
      if (seen.has(k)) throw new Error("duplicate object key");
      seen.add(k);
    }
    return `{${keys.map((k) => `${escapeJsonString(k)}:${canonicalize(value[k])}`).join(",")}}`;
  }
  throw new Error("unsupported canonical value");
}

function sha256Hex(canonical) {
  return createHash("sha256").update(canonical, "utf8").digest("hex");
}

function asConstUnion(constName, typeName, values) {
  const lits = values.map((v) => `  "${v}",`).join("\n");
  return `export const ${constName} = [\n${lits}\n] as const;\nexport type ${typeName} = (typeof ${constName})[number];\n`;
}

