const truth = ["SATISFIED", "NOT_SATISFIED", "UNKNOWN"];
const projectionValues = [...truth, "ABSENT"];
const vectors = [];

function allFold(values) {
  if (values.includes("NOT_SATISFIED")) return "NOT_SATISFIED";
  if (values.includes("UNKNOWN")) return "UNKNOWN";
  return "SATISFIED";
}
function anyFold(values) {
  if (values.includes("SATISFIED")) return "SATISFIED";
  if (values.includes("UNKNOWN")) return "UNKNOWN";
  return "NOT_SATISFIED";
}
function atLeast(values, k) {
  const n = values.length;
  if (n === 0) return "ABSENT";
  const s = values.filter((v) => v === "SATISFIED").length;
  const u = values.filter((v) => v === "UNKNOWN").length;
  if (s >= k) return "SATISFIED";
  if (s + u < k) return "NOT_SATISFIED";
  return "UNKNOWN";
}

